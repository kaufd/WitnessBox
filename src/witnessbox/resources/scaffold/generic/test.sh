#!/bin/bash
# test.sh заготовки ebt/ для любого инструмента тестов (ebt-gate --scaffold generic).
#
# Договор гейта: рабочая папка — корень чистого клона; OUT_DIR — пустой абсолютный
# каталог результатов прогона. Аргументы — слова из EBT_TESTS; они передаются
# команде отдельными словами, без eval. Коды: 0 — тесты прошли, 1 — тесты
# выполнились и упали, 2 — ошибка исполнения. Свидетельства собираются в OUT_DIR
# при любом исходе тестов.
#
# Команда тестов задаётся переменной окружения:
#   EBT_TEST_CMD        обязательная строка команды; исполняется как bash -c.
#                       Слова EBT_TESTS добавляются к простой команде отдельными
#                       argv. Символы #, ;, &, | и \ в команде требуют явного
#                       "$@"/"$*" — иначе аргументы потерялись бы или выполнились
#                       отдельной командой (код 2). Позиционные $1…$9 и ${1}…${9}
#                       без "$@" запрещены по той же причине; "$@" в одинарных
#                       кавычках не считается ссылкой. Хвостовые переводы строк и
#                       пробелы отбрасываются;
#   EBT_EVIDENCE_DIR    каталог JSONL от тестов, по умолчанию build/ebt;
#   EBT_TEST_FAIL_CODES коды команды, означающие «тесты выполнились и упали»,
#                       через пробел, по умолчанию 1.
#
# Отображение кодов: 0 → 0; код из EBT_TEST_FAIL_CODES → 1; всё остальное → 2.
# Инструменты вроде Maven и Gradle возвращают 1 и на упавшие тесты, и на сломанную
# сборку: если это важно, разбирайте отчёты в своём test.sh или задайте точный
# набор кодов в EBT_TEST_FAIL_CODES (docs/scaffold.md).
set -uo pipefail

[ -n "${OUT_DIR:-}" ] || { echo "test.sh: нужен OUT_DIR (запуск через ebt-gate)" >&2; exit 2; }

[ -n "${EBT_TEST_CMD:-}" ] || {
  echo "test.sh: задайте EBT_TEST_CMD — команду тестов проекта (docs/scaffold.md, стек generic)" >&2
  exit 2
}

evidence_dir=${EBT_EVIDENCE_DIR:-build/ebt}
fail_codes=${EBT_TEST_FAIL_CODES:-1}

# Свидетельства прошлого прогона не должны пережить текущий, даже если тесты упали.
rm -rf "$evidence_dir" || exit 2

# Хвостовые переводы строк и пробелы из YAML-блока не должны менять команду.
trim_command() {
  local value=$1
  while [ -n "$value" ]; do
    case ${value:${#value}-1:1} in
      ' '|$'\t'|$'\n'|$'\r') value=${value%?} ;;
      *) break ;;
    esac
  done
  printf '%s' "$value"
}

cmd=$(trim_command "$EBT_TEST_CMD")
[ -n "$cmd" ] || { echo "test.sh: EBT_TEST_CMD пуст" >&2; exit 2; }

# Команда должна быть простой: слова EBT_TESTS добавляются к ней отдельными argv.
# Shell-синтаксис не разбираем: без явного "$@" он либо съест аргументы, либо
# выполнит их отдельной командой. В сложном случае команда сама раскрывает "$@"/
# "$*" и получает EBT_TESTS позиционными параметрами.
uses_args=0
case $cmd in *'$@'*|*'$*'*|*'${@}'*|*'${*}'*) uses_args=1 ;; esac
double_args=0
case $cmd in *'"$@"'*|*'"$*"'*|*'"${@}"'*|*'"${*}"'*) double_args=1 ;; esac

# "$@" в одинарных кавычках — литерал: аргументы бы потерялись. Требуем двойные
# кавычки, если в команде вообще есть одинарные.
case $cmd in
  *"'"*)
    if [ "$uses_args" -eq 1 ] && [ "$double_args" -eq 0 ]; then
      echo "test.sh: EBT_TEST_CMD: \"\$@\" должен быть в двойных кавычках, не в одинарных" >&2
      exit 2
    fi ;;
esac
case $cmd in
  *'#'*)
    case ${cmd%%#*} in
      *'$@'*|*'$*'*|*'${@}'*|*'${*}'*) ;;
      *) echo "test.sh: в EBT_TEST_CMD есть #, но нет \"\$@\"; упростите команду или добавьте \"\$@\"" >&2
         exit 2 ;;
    esac ;;
esac
case $cmd in
  *';'*|*'&'*|*'|'*|*'\'*)
    if [ "$uses_args" -eq 0 ]; then
      echo "test.sh: EBT_TEST_CMD содержит ;, &, | или \\, но не ссылается на \"\$@\"" >&2
      exit 2
    fi ;;
esac
case $cmd in
  *'$1'*|*'$2'*|*'$3'*|*'$4'*|*'$5'*|*'$6'*|*'$7'*|*'$8'*|*'$9'*|\
  *'${1'*|*'${2'*|*'${3'*|*'${4'*|*'${5'*|*'${6'*|*'${7'*|*'${8'*|*'${9'*)
    if [ "$uses_args" -eq 0 ]; then
      echo "test.sh: EBT_TEST_CMD: используйте \"\$@\", а не позиционные \$1…\$9" >&2
      exit 2
    fi ;;
esac

if [ "$uses_args" -eq 1 ]; then
  # Команда сама раскрывает "$@": аргументы передаются позиционными параметрами.
  bash -c "$cmd" _ "$@"
else
  # Слова EBT_TESTS — отдельные argv последней команды, без eval и повторного разбора.
  bash -c "$cmd"' "$@"' _ "$@"
fi
rc=$?

# Свидетельства копируются при любом исходе: красный прогон тоже проверяется чекером.
mkdir -p "$OUT_DIR" || exit 2
shopt -s nullglob
evidence=("$evidence_dir"/*.jsonl)
if [ ${#evidence[@]} -gt 0 ]; then
  cp "${evidence[@]}" "$OUT_DIR"/ || exit 2
fi

[ "$rc" -eq 0 ] && exit 0
for code in $fail_codes; do
  [ "$rc" = "$code" ] && exit 1
done
exit 2
